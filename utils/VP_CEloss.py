""" Contains custom loss functions. """
import numpy as np
import cvxpy as cp
import torch
import torch.nn as nn
from torch.autograd import Function

class VP_CE(nn.Module):
    """ Implements the Vertex Proportion (VP) loss with the crossentropy (CE) cost.""" 

    def __init__(self, dim, solver=cp.ECOS):
        """ Initializes the module.
       
        Args:
            dim - The dimension of the space (# of classes)
            
            solver - Which cvxpy solver to use."""
       
        super(VP_CE, self).__init__()
       
        self.dim = dim     
        self.solver = solver
        self._prob = None
       
    def _create_cvxpy(self, N,target):
        """ Function to create the cvxpy optimization problem for a given
        number of data points.
        
        Args:
            N - Number of data points that will be input (bag size).
            target - A [dim] element tensor which contains the target probabilites for the bag."""
        
        t_np = target.detach().cpu().numpy().reshape(-1,1)#target
        C = cp.Parameter((N, self.dim), name='C', nonneg=True)#Cost matrix
        self.z_cp = cp.Variable((self.dim, 1), name = 'z_cp')#Phi
        self.s_cp = cp.Variable((N, 1), name = 's_cp')#S       

        obj = cp.Maximize(t_np.T@self.z_cp - 1.0/N*cp.sum(self.s_cp))
        constraints = [self.s_cp@np.ones((1,self.dim)) >=  np.ones((N,1))@self.z_cp.T - C]      
        self._prob = cp.Problem(obj, constraints)         

    def forward(self, pred, target):
        """ Computes the value of the loss function.
        
        Solves the full linear program to compute the exact value of the optimization problem. 
        
        Args:
            pred - A [N x dim] tensor which contains the network predictions.
            Note that it is assumed that each row of pred is on the simplex
            (i.e., non-zero entries which sum to 1), such as the output of a
            softmax layer.

            target - A [dim] element tensor which contains the target probabilites
            for the bag. 
            
        Returns:
            opt_val - The optimal value of the loss function."""
            
        N = pred.shape[0]
        #create linear problem
        self._create_cvxpy(N,target)
        
        #Call the solving function object to support pytorch.autograd
        opt_val = CE_solve(pred, self._prob, self.solver)
        #self.assignment = np.argmax(2*pred.detach().cpu().numpy() + np.ones((N,1))*self.z_cp.T.value,axis=1)
        return opt_val
        
    
class CE_Simplex_Function(Function):
    """ Class to compute the VP loss using a linear program solver.
    
    This function is meant to be called by a VP_CE object which has created
    the necessary cvxpy optimization solver."""
    
    @staticmethod
    def forward(ctx, pred, cvxpy_prob, solver):
        """ Runs the cvxpy problem and saves the dual variable for the backward pass.
        
        Args:
            ctx - pytorch internal.
            pred - Predicted variables (as pytorch tensor).
            cvxpy_prob - The cvxpy problem generated by VP_CE.
            
        Returns:
            opt_val - The function value.
            (Other values of optimization problem such as variables can be
            accessed in cvxpy_prob which is modified in place)."""
            
        #Compute cost matrix and make a numpy copy of the it.
        C = -torch.log(pred+1e-7)+1e-6
        C_np = C.detach().cpu().numpy()

        #Save the data type and device of the input so we can match with the
        #output and gradient.
        dtype = pred.dtype
        device = pred.device
             
        #Test the cvxpy problem is what we're expecting.
        assert cvxpy_prob.parameters()[0].name()=='C'
        cvxpy_prob.parameters()[0].value = C_np #assign the actual value to the params
        
        try:
            cvxpy_prob.solve(solver=solver, warm_start=True,verbose = False)
        except:
            cvxpy_prob.solve(solver=solver, warm_start=True,verbose = True, feastol = 1e-05, reltol=1e-03, abstol=1e-03)
            print('exception')             
        #Save the dual variables of the optimization problem to return the 
        #gradient later during backward()
        dual_var = cvxpy_prob.constraints[0].dual_value

        dual_var = torch.tensor(dual_var, dtype = dtype, device = device)
        
        ctx.save_for_backward(dual_var,pred)
        
        #Return the optimal value
        opt_val = cvxpy_prob.value
        opt_val = torch.tensor(opt_val, dtype = dtype, device = device)
        return opt_val
    
    @staticmethod
    def backward(ctx, grad_output):
        """ Part of the gradient is already calculated in the forward function."""       
        dual_var, pred = ctx.saved_tensors
        predgrad = -torch.div(dual_var,pred+1e-7)
        if ctx.needs_input_grad[0]:
            return grad_output*predgrad, None, None
        else:
            return None, None, None

CE_solve = CE_Simplex_Function.apply
    
